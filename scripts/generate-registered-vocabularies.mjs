// Generates src/registered-vocabularies.generated.ts from the protocol's registered vocabularies.
//
//   node scripts/generate-registered-vocabularies.mjs            write the module from the sibling protocol
//   node scripts/generate-registered-vocabularies.mjs --check    exit 1 when the committed module differs
//   node scripts/generate-registered-vocabularies.mjs --vocabularies <dir> [--out <path>]
//
// For each kind, a verifier holds the version of the registered vocabulary built into it unless the
// operator supplies another (verification-vocabularies.md section 8). The built-in versions are
// loquitur-protocol's `vocabularies/<kind>.json`, embedded here as their exact text with the
// SHA-256 of their bytes, so that the package reads no file at run time (the browser entry point
// included) and a report can name exactly what it held. The text is written with every character
// outside printable ASCII escaped, so the module is ASCII whatever the files hold, and generation
// stops on bytes that are not UTF-8 or that begin with a byte-order mark.
//
// Called directly; it has no npm script. test/registered-vocabularies.test.ts compares the
// committed module with this rendering of the sibling loquitur-protocol files.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const PACKAGE_DIR = join(dirname(fileURLToPath(import.meta.url)), "..");
export const DEFAULT_VOCABULARIES = join(PACKAGE_DIR, "..", "loquitur-protocol", "vocabularies");
export const DEFAULT_OUT = join(PACKAGE_DIR, "src", "registered-vocabularies.generated.ts");
/** The kinds of verification-vocabularies.md section 5, in its order. */
export const KINDS = ["asset_type", "workflow", "anchoring_method"];

const strictUtf8 = new TextDecoder("utf-8", { fatal: true, ignoreBOM: true });

/** A string literal for `text` in which every character outside printable ASCII is escaped. */
function asciiLiteral(text) {
  return JSON.stringify(text).replace(/[^\x20-\x7e]/g, (ch) => `\\u${ch.charCodeAt(0).toString(16).padStart(4, "0")}`);
}

/** The bytes of each kind's vocabulary file under `directory`. */
export function readVocabularies(directory) {
  return Object.fromEntries(KINDS.map((kind) => [kind, readFileSync(join(directory, `${kind}.json`))]));
}

/** The generated module's text for the bytes of each kind's vocabulary file. */
export function renderRegisteredVocabularies(files) {
  const lines = [
    "// Generated by scripts/generate-registered-vocabularies.mjs from",
    "// loquitur-protocol/vocabularies/<kind>.json. Do not edit: regenerate, and",
    "// test/registered-vocabularies.test.ts checks the two agree.",
    "",
    "/** The text of each registered vocabulary built into this verifier (verification-vocabularies.md section 8), exactly as the protocol's file holds it. */",
    "export const REGISTERED_VOCABULARIES: Readonly<Record<\"asset_type\" | \"workflow\" | \"anchoring_method\", string>> = {",
  ];
  const digests = {};
  for (const kind of KINDS) {
    const bytes = files[kind];
    if (bytes === undefined) throw new Error(`no registered vocabulary of the kind ${kind}`);
    if (bytes.length >= 3 && bytes[0] === 0xef && bytes[1] === 0xbb && bytes[2] === 0xbf) {
      throw new Error(`the ${kind} vocabulary begins with a byte-order mark`);
    }
    const text = strictUtf8.decode(bytes);
    digests[kind] = createHash("sha256").update(bytes).digest("hex");
    const parts = text.split(/(?<=\n)/);
    lines.push(`  ${kind}:`);
    parts.forEach((part, index) => lines.push(`    ${asciiLiteral(part)}${index === parts.length - 1 ? "," : " +"}`));
  }
  lines.push("};", "");
  lines.push("/** The SHA-256 of each embedded vocabulary's bytes, lowercase hexadecimal. */");
  lines.push("export const REGISTERED_VOCABULARY_SHA256: Readonly<Record<\"asset_type\" | \"workflow\" | \"anchoring_method\", string>> = {");
  for (const kind of KINDS) lines.push(`  ${kind}: ${JSON.stringify(digests[kind])},`);
  lines.push("};", "");
  return lines.join("\n");
}

function main(argv) {
  const arg = (name) => {
    const i = argv.indexOf(name);
    return i >= 0 ? argv[i + 1] : undefined;
  };
  const directory = resolve(arg("--vocabularies") ?? DEFAULT_VOCABULARIES);
  const outPath = resolve(arg("--out") ?? DEFAULT_OUT);
  const text = renderRegisteredVocabularies(readVocabularies(directory));
  if (argv.includes("--check")) {
    let current = null;
    try {
      current = readFileSync(outPath, "utf8");
    } catch {
      current = null;
    }
    if (current !== text) {
      process.stderr.write(`registered vocabularies out of date: ${outPath}\n`);
      return 1;
    }
    process.stdout.write("registered vocabularies up to date\n");
    return 0;
  }
  writeFileSync(outPath, text);
  process.stdout.write(`wrote ${outPath}\n`);
  return 0;
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  process.exitCode = main(process.argv.slice(2));
}
