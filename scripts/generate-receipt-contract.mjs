// Generates src/receipt-contract.generated.ts from the protocol's verification receipt schema.
//
//   node scripts/generate-receipt-contract.mjs            write the module from the sibling schema
//   node scripts/generate-receipt-contract.mjs --check    exit 1 when the committed module differs
//   node scripts/generate-receipt-contract.mjs --schema <path> [--out <path>]
//
// The receipt is a closed contract (verification_receipt.schema.json, additionalProperties
// false), and this verifier validates it whenever a bundle carries one. The rules are taken
// from the schema, not written a second time by hand: a hand-kept copy of the 61 reason codes
// or of the verified_at pattern is how the two implementations drift. Only the keywords the
// validator in src/receipt-contract.ts enforces are carried; annotations are dropped; any other
// keyword stops the generation, so a schema that grows a constraint cannot be half-enforced.
//
// Called directly; it has no npm script. test/receipt-contract.test.ts compares the committed
// module with this rendering of the sibling loquitur-protocol schema.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const PACKAGE_DIR = join(dirname(fileURLToPath(import.meta.url)), "..");
export const DEFAULT_SCHEMA = join(PACKAGE_DIR, "..", "loquitur-protocol", "docs", "specification", "schemas",
  "verification_receipt.schema.json");
export const DEFAULT_OUT = join(PACKAGE_DIR, "src", "receipt-contract.generated.ts");

const ANNOTATIONS = new Set(["$id", "$schema", "title", "description", "example", "examples"]);
const ENFORCED = ["type", "const", "enum", "pattern", "minLength", "minimum", "minItems", "uniqueItems", "items",
  "required", "additionalProperties", "properties"];

function rule(node, path) {
  if (node === null || typeof node !== "object" || Array.isArray(node)) throw new Error(`${path}: not a schema object`);
  for (const key of Object.keys(node)) {
    if (!ANNOTATIONS.has(key) && !ENFORCED.includes(key)) throw new Error(`${path}: unsupported keyword ${key}`);
  }
  const out = {};
  for (const key of ENFORCED) {
    if (!(key in node)) continue;
    const value = node[key];
    if (key === "type") out.types = Array.isArray(value) ? [...value] : [value];
    else if (key === "items") out.items = rule(value, `${path}.items`);
    else if (key === "properties") {
      out.properties = Object.fromEntries(Object.keys(value).sort().map((name) => [name, rule(value[name], `${path}.properties.${name}`)]));
    } else if (key === "additionalProperties") {
      if (typeof value !== "boolean") throw new Error(`${path}: additionalProperties must be a boolean here`);
      out.additionalProperties = value;
    } else out[key] = value;
  }
  return out;
}

/** The generated module's text for a parsed schema. */
export function renderReceiptContract(schema) {
  const contract = rule(schema, "$");
  return [
    "// Generated by scripts/generate-receipt-contract.mjs from",
    "// loquitur-protocol/docs/specification/schemas/verification_receipt.schema.json. Do not edit:",
    "// regenerate, and test/receipt-contract.test.ts checks the two agree.",
    'import type { ContractRule } from "./contract-rule.js";',
    "",
    `export const RECEIPT_CONTRACT: ContractRule = ${JSON.stringify(contract, null, 2)};`,
    "",
  ].join("\n");
}

function main(argv) {
  const arg = (name) => {
    const i = argv.indexOf(name);
    return i >= 0 ? argv[i + 1] : undefined;
  };
  const schemaPath = resolve(arg("--schema") ?? DEFAULT_SCHEMA);
  const outPath = resolve(arg("--out") ?? DEFAULT_OUT);
  const text = renderReceiptContract(JSON.parse(readFileSync(schemaPath, "utf8")));
  if (argv.includes("--check")) {
    let current = null;
    try {
      current = readFileSync(outPath, "utf8");
    } catch {
      current = null;
    }
    if (current !== text) {
      process.stderr.write(`receipt contract out of date: ${outPath}\n`);
      return 1;
    }
    process.stdout.write("receipt contract up to date\n");
    return 0;
  }
  writeFileSync(outPath, text);
  process.stdout.write(`wrote ${outPath}\n`);
  return 0;
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  process.exitCode = main(process.argv.slice(2));
}
