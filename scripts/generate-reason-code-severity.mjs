// Generates src/reason-code-severity.generated.ts from the protocol's reason-code catalog.
//
//   node scripts/generate-reason-code-severity.mjs            write the module from the sibling catalog
//   node scripts/generate-reason-code-severity.mjs --check    exit 1 when the committed module differs
//   node scripts/generate-reason-code-severity.mjs --catalog <path> --schema <path> [--out <path>]
//
// A registry entry's verdict must be the verdict its reason codes derive (verdict-grounds.md VG-3),
// and deriving it needs each code's severity, which lives in the catalog, not in any schema. The
// table is taken from the catalog rather than typed a second time, and generation stops when a
// catalog entry has no usable severity or when the catalog and the registry entry's reason_codes
// enum name different codes.
//
// Called directly; it has no npm script. test/verdict-grounds.test.ts compares the committed
// module with this rendering of the sibling loquitur-protocol catalog.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const PACKAGE_DIR = join(dirname(fileURLToPath(import.meta.url)), "..");
const SPECIFICATION = join(PACKAGE_DIR, "..", "loquitur-protocol", "docs", "specification");
export const DEFAULT_CATALOG = join(SPECIFICATION, "reason-codes", "v2.0", "catalog.json");
export const DEFAULT_SCHEMA = join(SPECIFICATION, "schemas", "registry_entry.schema.json");
export const DEFAULT_OUT = join(PACKAGE_DIR, "src", "reason-code-severity.generated.ts");

const SEVERITIES = ["info", "warn", "review", "fail"];

/** The generated module's text for a parsed catalog and registry-entry schema. */
export function renderReasonCodeSeverity(catalog, registryEntrySchema) {
  const severities = {};
  for (const code of Object.keys(catalog.entries).sort()) {
    const entry = catalog.entries[code];
    if (entry === null || typeof entry !== "object" || entry.code !== code || !SEVERITIES.includes(entry.severity)) {
      throw new Error(`catalog entry ${code}: no usable code and severity`);
    }
    severities[code] = entry.severity;
  }
  const enumCodes = [...registryEntrySchema.properties.reason_codes.items.enum].sort();
  if (JSON.stringify(enumCodes) !== JSON.stringify(Object.keys(severities))) {
    throw new Error("the catalog and the registry entry's reason_codes enum name different codes");
  }
  if (typeof catalog.reason_code_vocabulary !== "string") throw new Error("catalog has no reason_code_vocabulary");
  return [
    "// Generated by scripts/generate-reason-code-severity.mjs from",
    "// loquitur-protocol/docs/specification/reason-codes/v2.0/catalog.json. Do not edit: regenerate,",
    "// and test/verdict-grounds.test.ts checks the two agree.",
    "",
    `export const REASON_CODE_VOCABULARY = ${JSON.stringify(catalog.reason_code_vocabulary)};`,
    "",
    "export type ReasonCodeSeverity = \"info\" | \"warn\" | \"review\" | \"fail\";",
    "",
    `export const REASON_CODE_SEVERITY: Readonly<Record<string, ReasonCodeSeverity>> = ${JSON.stringify(severities, null, 2)};`,
    "",
  ].join("\n");
}

function main(argv) {
  const arg = (name) => {
    const i = argv.indexOf(name);
    return i >= 0 ? argv[i + 1] : undefined;
  };
  const catalog = JSON.parse(readFileSync(resolve(arg("--catalog") ?? DEFAULT_CATALOG), "utf8"));
  const schema = JSON.parse(readFileSync(resolve(arg("--schema") ?? DEFAULT_SCHEMA), "utf8"));
  const outPath = resolve(arg("--out") ?? DEFAULT_OUT);
  const text = renderReasonCodeSeverity(catalog, schema);
  if (argv.includes("--check")) {
    let current = null;
    try {
      current = readFileSync(outPath, "utf8");
    } catch {
      current = null;
    }
    if (current !== text) {
      process.stderr.write(`reason-code severity table out of date: ${outPath}\n`);
      return 1;
    }
    process.stdout.write("reason-code severity table up to date\n");
    return 0;
  }
  writeFileSync(outPath, text);
  process.stdout.write(`wrote ${outPath}\n`);
  return 0;
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  process.exitCode = main(process.argv.slice(2));
}
